// Cell centers as integer percentages, floored by less than one percentage point.
// Equivalent to (col + 0.5) / 7 * 100 and (row + 0.5) / 9 * 100 before rounding.
// Original integer grid coordinates stay in NODES; game state stores only a node id.
function gridPosition(col: number, row: number): { x: number; y: number } {
  return { x: Math.floor((2 * col + 1) * 50 / 7), y: Math.floor((2 * row + 1) * 50 / 9) };
}

// All §3.2 fares are destination entry tolls. D links retain the nominal 300 fee:
// consuming invite and waiving its toll belong to movement, not this graph table.
export const WORLD: WorldNode[] = (Object.entries(NODES) as [MapId, NodeRow[]][]).flatMap(([map, rows]) =>
  rows.map(([id, col, row, kind, place, next, cross]) => ({
    id: `${map}-${id}`, map, kind, place, ...gridPosition(col, row),
    next: next.map(id => `${map}-${id}`),
    ...(cross ? { cross: cross.map(destination => ({
      to: `${destination}-o1`, fare: MAPS[destination].fareIn,
      ...(MAPS[destination].gate ? { gate: MAPS[destination].gate } : {}),
    })) } : {}),
  })),
);
